"""Code lists used by the oracle, the facts extractor and the agent tools.

Every code is given as it appears in Synthea v4.0.0 CSV output (code and
DESCRIPTION text). How each list was found:

- "source": grep of the v4.0.0 module JSON files (src/main/resources/modules)
  and resource tables (htn_drugs.csv, biometrics.yml) for the code.
- "data": seen in the CSV output of the development runs (day-0 pilots,
  seeds 20261118 and 20261119, and the dev run, seed 20261120).
- "source only": defined in a module but not seen in any development run.

scripts/check_codes.py re-checks every list against a database and prints
codes in the data that look relevant but are not listed.

Conditions and procedures are SNOMED-CT unless noted, medications RxNorm,
observations LOINC. Codes are strings, as in the CSV files.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Code:
    code: str
    display: str
    group: str = ""  # subgroup within a list (ASCVD type, drug class, ...)
    alt_displays: tuple[str, ...] = field(default_factory=tuple)
    note: str = ""


def _index(codes: list[Code]) -> dict[str, Code]:
    out: dict[str, Code] = {}
    for c in codes:
        if c.code in out:
            raise ValueError(f"duplicate code {c.code}")
        out[c.code] = c
    return out


